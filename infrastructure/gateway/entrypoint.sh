#!/bin/sh
# Gateway start: turn TRUSTED_PROXY_CIDRS into nginx's real-address block,
# then hand off to nginx.
#
# Behind a Hub, the request that reaches this nginx has already crossed
# cloudflared (or the Tailscale sidecar) and Traefik, and `$remote_addr` is
# Traefik. The API takes its client address from the last X-Forwarded-For hop
# nginx appends, so every tunnelled visitor arrived as Traefik: one address for
# everyone, which turned the per-address login throttle into a lockout anyone
# could trigger for everyone and made the address half of session binding a
# no-op. See the 2026-09-24 audit, item 10c.
#
# The Hub passes the hops it can vouch for — Traefik's own address and the
# edge subnet cloudflared and Tailscale sit on — as TRUSTED_PROXY_CIDRS. With
# them, nginx walks the forwarded chain back past those hops to the real
# client (`real_ip_recursive`), and that is what it forwards to the API.
#
# Unset or empty: nothing is trusted, and behaviour is exactly as before. That
# is the right default for a standalone install, where a LAN client reaches
# this nginx directly and any trusted range that included it would let it
# choose its own address.
set -eu

CONF="${TRUSTED_PROXIES_CONF:-/etc/nginx/trusted-proxies.conf}"
CIDRS="${TRUSTED_PROXY_CIDRS:-}"

# Accept IPv4 (with optional /n) and IPv6 (with optional /n); refuse anything
# else rather than letting a stray token become a directive.
valid_cidr() {
  printf '%s' "$1" | grep -Eq '^([0-9]{1,3}\.){3}[0-9]{1,3}(/[0-9]{1,2})?$' && return 0
  printf '%s' "$1" | grep -Eq '^[0-9a-fA-F:]*:[0-9a-fA-F:]*(/[0-9]{1,3})?$' && return 0
  return 1
}

tmp="$CONF.tmp"
{
  echo "# Generated by entrypoint.sh from TRUSTED_PROXY_CIDRS. Do not edit."
  count=0
  for token in $(printf '%s' "$CIDRS" | tr ',' ' '); do
    if valid_cidr "$token"; then
      echo "set_real_ip_from $token;"
      count=$((count + 1))
    else
      echo "[gateway] ignoring invalid TRUSTED_PROXY_CIDRS entry: $token" >&2
    fi
  done
  if [ "$count" -gt 0 ]; then
    echo "real_ip_header X-Forwarded-For;"
    echo "real_ip_recursive on;"
  fi
} > "$tmp"
mv -f "$tmp" "$CONF"

if [ -n "$CIDRS" ]; then
  echo "[gateway] trusting forwarded addresses from: $CIDRS"
fi

exec "$@"
