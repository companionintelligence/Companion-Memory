#!/bin/sh
# Gateway start: turn TRUSTED_PROXY_CIDRS into nginx's real-address block,
# then hand off to nginx.
#
# Behind a Hub, the request that reaches this nginx has already crossed
# cloudflared (or the Tailscale sidecar) and Traefik, and `$remote_addr` is
# Traefik. The API takes its client address from the last X-Forwarded-For hop
# nginx appends, so every tunnelled visitor arrived as Traefik: one address for
# everyone, which turned the per-address login throttle into a lockout anyone
# could trigger for everyone and made the address half of session binding a
# no-op. See the 2026-09-24 audit, item 10c.
#
# The Hub passes the hops it can vouch for — Traefik's own address and the
# edge subnet cloudflared and Tailscale sit on — as TRUSTED_PROXY_CIDRS. With
# them, nginx walks the forwarded chain back past those hops to the real
# client (`real_ip_recursive`), and that is what it forwards to the API.
#
# Unset or empty: nothing is trusted, and behaviour is exactly as before. That
# is the right default for a standalone install, where a LAN client reaches
# this nginx directly and any trusted range that included it would let it
# choose its own address.
set -eu

CONF="${TRUSTED_PROXIES_CONF:-/etc/nginx/trusted-proxies.conf}"
CIDRS="${TRUSTED_PROXY_CIDRS:-}"

# Accept IPv4 (with optional /n) and IPv6 (with optional /n); refuse anything
# else rather than letting a stray token become a directive.
valid_cidr() {
  printf '%s' "$1" | grep -Eq '^([0-9]{1,3}\.){3}[0-9]{1,3}(/[0-9]{1,2})?$' && return 0
  printf '%s' "$1" | grep -Eq '^[0-9a-fA-F:]*:[0-9a-fA-F:]*(/[0-9]{1,3})?$' && return 0
  return 1
}

tmp="$CONF.tmp"
{
  echo "# Generated by entrypoint.sh from TRUSTED_PROXY_CIDRS. Do not edit."
  count=0
  for token in $(printf '%s' "$CIDRS" | tr ',' ' '); do
    if valid_cidr "$token"; then
      echo "set_real_ip_from $token;"
      count=$((count + 1))
    else
      echo "[gateway] ignoring invalid TRUSTED_PROXY_CIDRS entry: $token" >&2
    fi
  done
  if [ "$count" -gt 0 ]; then
    echo "real_ip_header X-Forwarded-For;"
    echo "real_ip_recursive on;"
  fi
} > "$tmp"
mv -f "$tmp" "$CONF"

if [ -n "$CIDRS" ]; then
  echo "[gateway] trusting forwarded addresses from: $CIDRS"
fi

# ── GATEWAY_ALLOWED_HOSTS: the Host names this gateway answers to.
#
# A page on any site can point its own DNS name at 127.0.0.1 (DNS rebinding)
# and then talk to this gateway as same-origin, under its own Host. On Memory
# Desktop, before the owner's first sign-in, that page could claim the
# appliance. With a list set, every other name gets 421 and nothing behind it
# is reached. IP literals and localhost names always pass: neither can be
# rebound, since no DNS lookup is involved. Nor can a single-label name
# (`ci-memory`, `gateway`): a page's Host is its own origin's name, and a name
# with no dot resolves only through Docker or the local network's search
# domain, never through DNS a remote site controls. CI-Hub's other apps reach
# Memory as `http://ci-memory:8642`.
#
# An entry starting with a dot is a suffix: `.ts.net` passes every name under
# ts.net (the Hub's tailnet names), not `ts.net` itself.
#
# Unset or empty: every Host passes, exactly as before. An appliance is reached
# under names this file cannot know (a custom domain, a LAN name), so only an
# install that knows its names sets it: Memory Desktop, and CI-Hub, which
# passes each Memory install the names its routes use.
HOSTS_CONF="${ALLOWED_HOSTS_CONF:-/etc/nginx/allowed-hosts.conf}"
ALLOWED="${GATEWAY_ALLOWED_HOSTS:-}"

tmp="$HOSTS_CONF.tmp"
{
  echo "# Generated by entrypoint.sh from GATEWAY_ALLOWED_HOSTS. Do not edit."
  echo 'map $host $gateway_host_allowed {'
  if [ -z "$ALLOWED" ]; then
    echo "  default 1;"
  else
    echo "  default 0;"
    echo "  localhost 1;"
    # Quoted: nginx reads a bare `{` in a map key as the start of a block.
    echo '  "~^[a-z0-9-]+\.localhost$" 1;'
    echo '  "~^[0-9]{1,3}(\.[0-9]{1,3}){3}$" 1;'
    echo '  "~^\[[0-9a-f:.]+\]$" 1;'
    # Single-label names (Docker service names and link aliases); see above.
    echo '  "~^[a-z0-9_-]+$" 1;'
    seen=" "
    for name in $(printf '%s' "$ALLOWED" | tr ',' ' ' | tr '[:upper:]' '[:lower:]'); do
      # A bare DNS name, or one after a dot (a suffix), only, so a stray token
      # cannot become a directive.
      if ! printf '%s' "$name" | grep -Eq '^\.?[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)*$'; then
        echo "[gateway] ignoring invalid GATEWAY_ALLOWED_HOSTS entry: $name" >&2
        continue
      fi
      # Once each, and not one the lines above pass already: nginx refuses a map
      # that names a key twice.
      case "$seen" in *" $name "*) continue ;; esac
      seen="$seen$name "
      if [ "$name" = localhost ] || printf '%s' "$name" | grep -Eq '^[a-z0-9-]+\.localhost$'; then
        continue
      fi
      case "$name" in
        .*)
          # Every name under the domain after the dot. Its dots are escaped,
          # so the pattern matches them and nothing else.
          echo "  \"~\\$(printf '%s' "$name" | sed 's/\./\\./g')\$\" 1;"
          ;;
        *)
          # A dotless name already passes as a single label.
          case "$name" in *.*) echo "  $name 1;" ;; esac
          ;;
      esac
    done
  fi
  echo "}"
} > "$tmp"
mv -f "$tmp" "$HOSTS_CONF"

if [ -n "$ALLOWED" ]; then
  echo "[gateway] answering only to IP addresses, localhost, single-label names and: $ALLOWED"
fi

exec "$@"
