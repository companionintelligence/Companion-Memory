#!/bin/sh
set -eu

# ──────────────────────────────────────────────────
# First-boot secret generation for Companion Intelligence.
#
# Creates the MASTER .env.secrets file (every generated
# credential, 0600, mounted into this container only) and
# then PROJECTS it: one .env.secrets per service under
# $SECRETS_PROJECTION_ROOT/<service>/, holding only the
# keys that service reads. Each service mounts its own
# projection at /run/secrets, so a compromised container
# holds its own credentials and nobody else's — the
# summarizer cannot read the JWT signing secret, the
# database cannot read the object-store password.
#
# The master used to be mounted, 0644, into all ten
# services (2026-09-24 audit, item 10d). The projection
# runs on EVERY boot, so a key added to the master by a
# later version of this script reaches its readers on the
# next start; the master's values are never rewritten.
#
# Idempotent — an existing master keeps every value, gains
# any key it is missing, and is re-projected.
# ──────────────────────────────────────────────────

SECRETS_FILE="${SECRETS_FILE:-/run/secrets/.env.secrets}"
# Where the per-service projections go. Standalone compose mounts one named
# volume per service at $ROOT/<service>; the Hub manifest binds the same
# subdirectories of its secrets host path. Either way each service then
# mounts its own subdirectory as /run/secrets and reads
# /run/secrets/.env.secrets exactly as before.
PROJECTION_ROOT="${SECRETS_PROJECTION_ROOT:-/run/secrets/services}"

random_password() {
  head -c 32 /dev/urandom | base64 | tr -d '/+=\n'
}

# Append a key that a later version of this script started requiring. Deployments
# that first booted before it existed keep their file (and every secret in it);
# they just gain the missing entry. Existing values are never rewritten — that
# would orphan data encrypted with the old key.
ensure_secret() {
  local key="$1" value="$2"
  if ! grep -q "^${key}=" "$SECRETS_FILE"; then
    echo "[bootstrap] Adding missing secret ${key} to ${SECRETS_FILE}"
    printf '%s=%s\n' "$key" "$value" >> "$SECRETS_FILE"
  fi
}

# ── Projection ───────────────────────────────────

# Write $PROJECTION_ROOT/<service>/.env.secrets holding the named keys, copied
# verbatim from the master. A key the master does not carry (DATABASE_HOST, an
# operator-only LLM_API_KEY) is simply absent, and the reader's own fallback
# applies. Written to a temp file and renamed, so a reader never sees a
# half-written projection. 0644 like the old shared file: several images read
# it as a non-root user (powersync uid 901, hbpe, memorizer, postgres, minio).
project() {
  local svc="$1"; shift
  local dir="$PROJECTION_ROOT/$svc"
  local out="$dir/.env.secrets"
  mkdir -p "$dir"
  {
    printf '# Generated by setup-secrets for the "%s" service — the keys it reads, nothing more.\n' "$svc"
    printf '# Do not edit: edit the master secrets file and restart setup-secrets.\n'
    for key in "$@"; do
      grep -m1 "^${key}=" "$SECRETS_FILE" || true
    done
  } > "$out.tmp"
  chmod 644 "$out.tmp"
  mv -f "$out.tmp" "$out"
}

# THE map: which service reads which key. Derived from each image's
# entrypoint (`get_secret NAME` calls) and the powersync/dbconnstr compose
# wrappers. A new key or a new reader is an edit here, on purpose — the
# alternative was every service seeing everything.
project_all() {
  # api, worker and migrate-database share the ci/api image and entrypoint.
  project api \
    DATABASE_USERNAME DATABASE_PASSWORD DATABASE_NAME \
    OBJECT_STORE_USERNAME OBJECT_STORE_PASSWORD \
    AUTH_TOKEN_SECRET AUTH_REFRESH_TOKEN_SECRET AUTH_SESSION_PEPPER \
    AUTH_FIELD_ENCRYPTION_KEY AUTH_CSRF_TOKEN_SECRET \
    POWERSYNC_JWT_SECRET SIDECAR_AUTH_SECRET LLM_API_KEY
  # Postgres itself bootstraps from the superuser credentials only.
  project database \
    DATABASE_ADMIN_USERNAME DATABASE_ADMIN_PASSWORD DATABASE_ADMIN_NAME
  # Creates the app and replication roles, so it needs all three identities.
  project setup-database \
    DATABASE_ADMIN_USERNAME DATABASE_ADMIN_PASSWORD DATABASE_ADMIN_NAME \
    DATABASE_USERNAME DATABASE_PASSWORD DATABASE_NAME \
    POWERSYNC_DATABASE_USERNAME POWERSYNC_DATABASE_PASSWORD
  project object-store \
    OBJECT_STORE_USERNAME OBJECT_STORE_PASSWORD
  # The sidecars: their database role plus the bearer the API presents.
  # Deliberately NOT the AUTH_* signing secrets — taking those away from the
  # sidecars was the point of the sidecar-auth change.
  project hbpe \
    DATABASE_USERNAME DATABASE_PASSWORD DATABASE_NAME SIDECAR_AUTH_SECRET
  project summary \
    DATABASE_USERNAME DATABASE_PASSWORD DATABASE_NAME SIDECAR_AUTH_SECRET LLM_API_KEY
  # Replication role for streaming, app role for its own storage schema, and
  # the HS256 key it validates client tokens with.
  project powersync \
    POWERSYNC_DATABASE_USERNAME POWERSYNC_DATABASE_PASSWORD \
    DATABASE_USERNAME DATABASE_PASSWORD DATABASE_NAME \
    POWERSYNC_JWT_SECRET
  # `dbconnstr` (tooling profile): prints the app connection string.
  project tooling \
    DATABASE_USERNAME DATABASE_PASSWORD DATABASE_NAME
  echo "[bootstrap] Projected per-service secrets under ${PROJECTION_ROOT}"
}

# ── Early Exit ───────────────────────────────────

if [ -f "$SECRETS_FILE" ]; then
  # 0600 now that only this container mounts the master (it was 0644 while
  # every service read it directly).
  chmod 600 "$SECRETS_FILE"
  echo "[bootstrap] Secrets file exists at ${SECRETS_FILE}, skipping generation."
  ensure_secret POWERSYNC_DATABASE_USERNAME powersync
  ensure_secret POWERSYNC_DATABASE_PASSWORD "$(random_password)"
  ensure_secret POWERSYNC_JWT_SECRET "$(random_password)"
  # Shared bearer the API presents to the Python sidecars (and they require).
  # Added 2026-09-24; existing appliances pick it up here on their next boot.
  ensure_secret SIDECAR_AUTH_SECRET "$(random_password)"
  project_all
  exit 0
fi

# ── Generation ───────────────────────────────────

echo "[bootstrap] First boot detected — generating unique deployment secrets..."
mkdir -p "$(dirname "$SECRETS_FILE")"

# ── Random Values ────────────────────────────────

DB_ADMIN_PASSWORD=$(random_password)
DB_APP_PASSWORD=$(random_password)
DB_SYNC_PASSWORD=$(random_password)
PS_JWT_SECRET=$(random_password)
S3_USERNAME=$(random_password)
S3_PASSWORD=$(random_password)
JWT_ACCESS_SECRET=$(head -c 64 /dev/urandom | base64 | tr -d '\n')
JWT_REFRESH_SECRET=$(head -c 64 /dev/urandom | base64 | tr -d '\n')
SESSION_PEPPER=$(head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')
ENCRYPTION_KEY=$(head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')
CSRF_SECRET=$(head -c 32 /dev/urandom | base64 | tr -d '\n')
SIDECAR_SECRET=$(random_password)

# ── Write Secrets File ───────────────────────────

cat > "$SECRETS_FILE" <<EOF
# Companion Intelligence Secrets
#
# Auto-generated on $(date -u +"%Y-%m-%dT%H:%M:%SZ")
#
# These secrets are unique to this deployment. If lost, encrypted data
# stored with these keys becomes unrecoverable.

# ──────────────────────────────
# PostgreSQL Admin (superuser)
# ──────────────────────────────
DATABASE_ADMIN_USERNAME=postgres
DATABASE_ADMIN_PASSWORD=${DB_ADMIN_PASSWORD}
DATABASE_ADMIN_NAME=postgres

# ──────────────────────────────
# Application Database (Companion API & Summary)
# ──────────────────────────────
DATABASE_USERNAME=companion
DATABASE_PASSWORD=${DB_APP_PASSWORD}
DATABASE_NAME=companion

# ──────────────────────────────
# PowerSync replication role (read-only, REPLICATION attribute)
# ──────────────────────────────
POWERSYNC_DATABASE_USERNAME=powersync
POWERSYNC_DATABASE_PASSWORD=${DB_SYNC_PASSWORD}
# Shared HS256 key between the two halves of sync auth: the API signs client
# tokens with it in /api/powersync/token, and the powersync service validates
# them against the same value as a JWKS oct key. The service wants it
# base64url-encoded; that is derived at container start rather than stored
# beside this one, so the two can never drift apart. See
# infrastructure/powersync/README.md.
POWERSYNC_JWT_SECRET=${PS_JWT_SECRET}

# ──────────────────────────────
# Object Store (MinIO)
# ──────────────────────────────
OBJECT_STORE_USERNAME=${S3_USERNAME}
OBJECT_STORE_PASSWORD=${S3_PASSWORD}

# ──────────────────────────────
# Authentication & Encryption
# ──────────────────────────────
AUTH_TOKEN_SECRET=${JWT_ACCESS_SECRET}
AUTH_REFRESH_TOKEN_SECRET=${JWT_REFRESH_SECRET}
AUTH_SESSION_PEPPER=${SESSION_PEPPER}
AUTH_FIELD_ENCRYPTION_KEY=${ENCRYPTION_KEY}
AUTH_CSRF_TOKEN_SECRET=${CSRF_SECRET}
SIDECAR_AUTH_SECRET=${SIDECAR_SECRET}
EOF

chmod 600 "$SECRETS_FILE"
echo "[bootstrap] Secrets generated and stored at ${SECRETS_FILE}"
project_all
