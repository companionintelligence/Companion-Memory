APP_STORE_ID="${APP_STORE_ID:-ci-marketplace}"
APP_NAME="${APP_NAME:-ci-memory}"
COMPOSE_PROJECT="${COMPOSE_PROJECT:-ci-memory_ci-marketplace}"

# The Hub container was ci-os-hub until Companion-Hub#1226 renamed it ci-hub.
# Use whichever is running unless HUB_CONTAINER says otherwise.
if [[ -z "${HUB_CONTAINER:-}" ]]; then
  for candidate in ci-hub ci-os-hub; do
    if [[ "$(docker inspect -f '{{.State.Running}}' "$candidate" 2>/dev/null)" == "true" ]]; then
      HUB_CONTAINER="$candidate"
      break
    fi
  done
  HUB_CONTAINER="${HUB_CONTAINER:-ci-hub}"
fi

# The Hub mounts every data folder from ${ROOT_FOLDER_HOST}/<name>, so its
# /data/apps mount names the root. That covers a Hub run from a checkout, whose
# data is not under ~/.local/share/companion-hub.
if [[ -z "${ROOT_FOLDER_HOST:-}" ]]; then
  hub_apps_host="$(docker inspect -f '{{range .Mounts}}{{if eq .Destination "/data/apps"}}{{.Source}}{{end}}{{end}}' "$HUB_CONTAINER" 2>/dev/null || true)"
  ROOT_FOLDER_HOST="${hub_apps_host:+$(dirname "$hub_apps_host")}"
  ROOT_FOLDER_HOST="${ROOT_FOLDER_HOST:-${HOME}/.local/share/companion-hub}"
  unset hub_apps_host
fi

APP_DIR_HOST="${ROOT_FOLDER_HOST}/apps/${APP_STORE_ID}/${APP_NAME}"
APP_ENV_HOST="${ROOT_FOLDER_HOST}/app-data/${APP_STORE_ID}/${APP_NAME}/app.env"
USER_CONFIG_DIR_HOST="${ROOT_FOLDER_HOST}/user-config/${APP_STORE_ID}/${APP_NAME}"
USER_ENV_HOST="${USER_CONFIG_DIR_HOST}/app.env"

# The Hub layers this file over the app's own docker-compose.yml on every
# compose call (start, restart, update and its own startup), so the image swap
# survives the Hub rewriting docker-compose.yml. The Hub skips it while custom
# configuration is turned off for the app.
USER_COMPOSE_HOST="${USER_CONFIG_DIR_HOST}/docker-compose.yml"
# An operator's own override, moved aside while a swap is in place.
USER_COMPOSE_BACKUP_HOST="${USER_COMPOSE_HOST}.before-pr-test"
# Where earlier versions of the deploy script wrote the override. The Hub never
# reads it, so a Hub restart dropped the swap.
LEGACY_OVERRIDE_HOST="${APP_DIR_HOST}/docker-compose.pr-test.yml"
# First line of every override the deploy script writes. Only a file that starts
# with it is treated as the script's own.
PR_TEST_MARKER="# Generated by hub-pr-test-deploy.sh"

HUB_APP_ENV="/app-data/${APP_STORE_ID}/${APP_NAME}/app.env"
HUB_USER_CONFIG_DIR="/data/user-config/${APP_STORE_ID}/${APP_NAME}"
HUB_USER_ENV="${HUB_USER_CONFIG_DIR}/app.env"
HUB_APP_DIR="/data/apps/${APP_STORE_ID}/${APP_NAME}"

require_app_env() {
  if [[ ! -f "$APP_ENV_HOST" ]]; then
    echo "Missing app.env: $APP_ENV_HOST" >&2
    echo "Set ROOT_FOLDER_HOST to the Hub's data root, or HUB_CONTAINER if the Hub container has another name." >&2
    exit 1
  fi
}

is_pr_test_override() {
  [[ -f "$1" ]] && [[ "$(head -n 1 "$1")" == "$PR_TEST_MARKER"* ]]
}

# Runs docker compose inside the Hub container with the same files the Hub
# passes (mirrors getBaseComposeArgsApp): app.env, the user app.env overlay,
# the app's docker-compose.yml and the user compose override. $1 is the compose
# subcommand. $2, when given, is a file in USER_CONFIG_DIR_HOST to layer in
# place of the user compose override.
hub_compose() {
  local user_compose="${2:-$USER_COMPOSE_HOST}"
  local env_args="--env-file ${HUB_APP_ENV}"
  local file_args="-f docker-compose.yml"

  if [[ -f "$USER_ENV_HOST" ]]; then
    env_args="${env_args} --env-file ${HUB_USER_ENV}"
  fi

  if [[ -f "$user_compose" ]]; then
    file_args="${file_args} -f ${HUB_USER_CONFIG_DIR}/$(basename "$user_compose")"
  fi

  docker exec "$HUB_CONTAINER" sh -c "
    set -eu
    cd '${HUB_APP_DIR}'
    docker compose ${env_args} --project-name '${COMPOSE_PROJECT}' ${file_args} $1
  "
}

# A recreated gateway gets a new address, but the Hub only rewrites Traefik's
# apps.yml when it starts, stops or restarts the app itself. Point Memory's
# upstream (the gateway's port 8642) at the new address on the network Traefik
# uses to reach it, which the gateway's traefik.docker.network label names.
refresh_traefik_upstream() {
  local gateway="${COMPOSE_PROJECT}-gateway-1"
  local apps_yml="${ROOT_FOLDER_HOST}/state/traefik/dynamic/apps.yml"
  local network gateway_ip

  echo "==> Refreshing Traefik upstream for the ci-memory gateway..."
  sleep 3
  network="$(docker inspect -f '{{index .Config.Labels "traefik.docker.network"}}' "$gateway" 2>/dev/null || true)"
  network="${network:-ci-hub_network}"
  gateway_ip="$(docker inspect -f "{{with index .NetworkSettings.Networks \"${network}\"}}{{.IPAddress}}{{end}}" "$gateway" 2>/dev/null || true)"

  if [[ -n "$gateway_ip" && -f "$apps_yml" ]] && grep -qE 'url: http://[0-9.]+:8642' "$apps_yml"; then
    sed -i -E "s|url: http://[0-9.]+:8642|url: http://${gateway_ip}:8642|" "$apps_yml"
    echo "    Traefik ci-memory upstream -> http://${gateway_ip}:8642 (${network})"
  else
    echo "    WARN: could not refresh Traefik apps.yml (gateway IP on ${network}: ${gateway_ip:-missing})"
    echo "    Restart ci-memory from the Hub UI, or restart ${HUB_CONTAINER}, to regenerate routing."
  fi
}
