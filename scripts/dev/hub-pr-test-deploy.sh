#!/usr/bin/env bash
# One-off: run locally built CI-Server api/gateway/hbpe/summary against Hub-managed ci-memory prod data.
# See docs/runbooks/one-off-prod-data-testing.md
set -euo pipefail

PR_TAG="${PR_TAG:-pr-onboarding-test}"
# Hub compose does not pass GPU devices into hbpe-service, so the image that
# lands on the box must be the CPU Dockerfile. Override GPU=rocm|cuda only if
# you also add device mounts in the override file.
GPU="${GPU:-cpu}"
HUB_CONTAINER="${HUB_CONTAINER:-ci-os-hub}"
APP_STORE_ID="${APP_STORE_ID:-ci-marketplace}"
APP_NAME="${APP_NAME:-ci-memory}"
COMPOSE_PROJECT="${COMPOSE_PROJECT:-ci-memory_ci-marketplace}"

ROOT_FOLDER_HOST="${ROOT_FOLDER_HOST:-${HOME}/.local/share/companion-hub}"
APP_DIR_HOST="${ROOT_FOLDER_HOST}/apps/${APP_STORE_ID}/${APP_NAME}"
APP_ENV_HOST="${ROOT_FOLDER_HOST}/app-data/${APP_STORE_ID}/${APP_NAME}/app.env"
USER_ENV_HOST="${ROOT_FOLDER_HOST}/user-config/${APP_STORE_ID}/${APP_NAME}/app.env"
OVERRIDE_FILE="${APP_DIR_HOST}/docker-compose.pr-test.yml"
REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"

API_IMAGE="ghcr.io/companionintelligence/companion/api:${PR_TAG}"
GATEWAY_IMAGE="ghcr.io/companionintelligence/companion/gateway:${PR_TAG}"
HBPE_IMAGE="ghcr.io/companionintelligence/companion/hbpe-service:${PR_TAG}"
SUMMARY_IMAGE="ghcr.io/companionintelligence/companion/summary-service:${PR_TAG}"

HUB_APP_ENV="/app-data/${APP_STORE_ID}/${APP_NAME}/app.env"
HUB_USER_ENV="/data/user-config/${APP_STORE_ID}/${APP_NAME}/app.env"
HUB_APP_DIR="/data/apps/${APP_STORE_ID}/${APP_NAME}"

usage() {
  cat <<EOF
Usage: $(basename "$0") [--frontend] [--skip-build] [--skip-migrate]

  Builds (unless --skip-build) and swaps ci-memory api + gateway + hbpe-service
  + summary-service to local images tagged ${PR_TAG}. Passes the same compose
  env files Hub uses: app.env plus optional user-config/app.env.

  --frontend        Rebuild only the web UI + gateway image, recreate gateway,
                    skip migrate. Use this for chrome/CSS/JS-only swaps.

Environment:
  PR_TAG            Image tag for local test images (default: pr-onboarding-test)
  GPU               HBPE Dockerfile variant (default: cpu — Hub does not pass GPU devices)
  ROOT_FOLDER_HOST  Hub data root (default: ~/.local/share/companion-hub)
  HUB_CONTAINER     Hub container name (default: ci-os-hub)

Rollback: $(dirname "$0")/hub-pr-test-rollback.sh
EOF
}

SKIP_BUILD=0
SKIP_MIGRATE=0
FRONTEND_ONLY=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --frontend) FRONTEND_ONLY=1; SKIP_MIGRATE=1; shift ;;
    --skip-build) SKIP_BUILD=1; shift ;;
    --skip-migrate) SKIP_MIGRATE=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $1" >&2; usage; exit 1 ;;
  esac
done

if [[ ! -f "$APP_ENV_HOST" ]]; then
  echo "Missing app.env: $APP_ENV_HOST" >&2
  exit 1
fi

RECREATE="api gateway hbpe-service summary-service"
if [[ "$FRONTEND_ONLY" -eq 1 ]]; then
  RECREATE="gateway"
fi

if [[ "$SKIP_BUILD" -eq 0 ]]; then
  if [[ "$FRONTEND_ONLY" -eq 1 ]]; then
    echo "==> Building web frontend + gateway image in ${REPO_ROOT}..."
    (cd "$REPO_ROOT/frontend/apps/web" && yarn build)
    (cd "$REPO_ROOT" && docker build -f infrastructure/gateway/Dockerfile -t ci/gateway:latest .)
  else
    echo "==> Building production images (GPU=${GPU}) in ${REPO_ROOT}..."
    (cd "$REPO_ROOT" && make build ENV=production GPU="$GPU")
  fi
fi

echo "==> Tagging local images as ${PR_TAG}..."
if [[ "$FRONTEND_ONLY" -eq 0 ]]; then
  docker tag ci/api:latest "$API_IMAGE"
  docker tag ci/hbpe-service:latest "$HBPE_IMAGE"
  docker tag ci/summary-service:latest "$SUMMARY_IMAGE"
fi
docker tag ci/gateway:latest "$GATEWAY_IMAGE"

# env_file must be declared on the services for the user-config overlay
# (NODE_OPTIONS, LLM endpoints, …) to reach the container environment —
# CLI --env-file only feeds compose variable substitution.
ENV_FILE_YAML="    env_file:
      - ${HUB_APP_ENV}"
if [[ -f "$USER_ENV_HOST" ]]; then
  ENV_FILE_YAML="${ENV_FILE_YAML}
      - ${HUB_USER_ENV}"
fi

cat > "$OVERRIDE_FILE" <<EOF
# Generated by hub-pr-test-deploy.sh — remove via hub-pr-test-rollback.sh
services:
  api:
    image: ${API_IMAGE}
    # Checkout can be ahead of the live DB. Do not apply those migrations
    # from this script unless the operator passes no --skip-migrate AND
    # has confirmed the SQL. Until then the API must boot anyway.
    environment:
      CI_SKIP_SCHEMA_CHECK: "1"
${ENV_FILE_YAML}
  gateway:
    image: ${GATEWAY_IMAGE}
${ENV_FILE_YAML}
  hbpe-service:
    image: ${HBPE_IMAGE}
    extra_hosts:
      - host.docker.internal:host-gateway
${ENV_FILE_YAML}
  summary-service:
    image: ${SUMMARY_IMAGE}
${ENV_FILE_YAML}
  migrate-database:
    image: ${API_IMAGE}
  database:
    shm_size: 1gb
EOF

echo "==> Wrote override: $OVERRIDE_FILE"

# Build env-file args for inside Hub (mirrors getBaseComposeArgsApp).
ENV_FILE_ARGS="--env-file ${HUB_APP_ENV}"
if [[ -f "$USER_ENV_HOST" ]]; then
  ENV_FILE_ARGS="${ENV_FILE_ARGS} --env-file ${HUB_USER_ENV}"
  echo "==> Will include user-config env overlay"
fi

run_compose() {
  local cmd="$1"
  docker exec "$HUB_CONTAINER" sh -c "
    set -eu
    cd '${HUB_APP_DIR}'
    docker compose ${ENV_FILE_ARGS} --project-name '${COMPOSE_PROJECT}' \
      -f docker-compose.yml -f docker-compose.pr-test.yml \
      ${cmd}
  "
}

if [[ "$SKIP_MIGRATE" -eq 0 ]]; then
  echo "==> Running migrate-database (applies pending SQL migrations)..."
  run_compose "run --rm migrate-database"
fi

echo "==> Recreating ${RECREATE} with PR images..."
run_compose "up -d --force-recreate --no-deps ${RECREATE}"

# Gateway gets a new Docker IP on recreate; Hub's Traefik file provider still points at the old one → 502.
echo "==> Refreshing Traefik upstream for ci-memory gateway..."
sleep 3
GATEWAY_IP="$(docker inspect "${COMPOSE_PROJECT}-gateway-1" --format '{{index .NetworkSettings.Networks "ci-os-hub_network" "IPAddress"}}' 2>/dev/null || true)"
TRAEFIK_APPS="${ROOT_FOLDER_HOST}/state/traefik/dynamic/apps.yml"
if [[ -n "$GATEWAY_IP" && -f "$TRAEFIK_APPS" ]]; then
  sed -i "s|url: http://172\\.18\\.0\\.[0-9]\\+:8642|url: http://${GATEWAY_IP}:8642|" "$TRAEFIK_APPS"
  echo "    Traefik ci-memory upstream -> http://${GATEWAY_IP}:8642"
else
  echo "    WARN: could not refresh Traefik apps.yml (gateway IP=${GATEWAY_IP:-missing})"
  echo "    Restart ci-memory from Hub UI or restart ci-os-hub to regenerate routing."
fi

echo ""
echo "==> Deploy complete."
echo "    docker ps --filter name=${COMPOSE_PROJECT} --format 'table {{.Names}}\t{{.Image}}\t{{.Status}}'"
echo "    docker logs ${COMPOSE_PROJECT}-api-1 --tail 40"
echo ""
echo "Rollback: ${REPO_ROOT}/scripts/dev/hub-pr-test-rollback.sh"
