/* eslint-disable @typescript-eslint/no-explicit-any */
import { Injectable } from '@nestjs/common';
import { InjectRepository } from '@nestjs/typeorm';
import { Repository } from 'typeorm';
import { z } from 'zod';
import { v4 as uuidv4, v7 as uuidv7 } from 'uuid';

import config from '@ci/configuration';
import { FileEntity } from '@ci/domains/files/entities/FileEntity';
import { FileService } from '@ci/domains/files/services/FileService';
import { EventService, Events } from '@ci/domains/events';

import { BaseTool } from './BaseTool';
import type { ToolExecutionContext } from './types';

// Input schema for the tool
const imageGenerationInputSchema = z.object({
  prompt: z.string().min(1, 'Prompt is required').max(4000, 'Prompt too long'),
  style: z.enum(['natural', 'vivid']).optional().default('natural'),
  size: z.enum(['1024x1024', '1792x1024', '1024x1792']).optional().default('1024x1024'),
  quality: z.enum(['standard', 'hd']).optional().default('standard'),
});

type ImageGenerationInput = z.infer<typeof imageGenerationInputSchema>;

// Output interface
interface ImageGenerationOutput {
  success: boolean;
  imageUrl: string;
  fileId: string;
  prompt: string;
  revisedPrompt?: string;
  message: string;
}

/**
 * Tool to generate images using OpenAI's DALL-E API
 * Integrates with the existing file storage system to save generated images
 */
@Injectable()
export class ImageGenerationTool extends BaseTool<ImageGenerationInput, ImageGenerationOutput> {

  readonly schema = {
    name: 'generate_image',
    description:
      'Generate images using AI based on text descriptions. Use this tool when users ask to create, generate, make, or draw images, pictures, artwork, or visual content.',
    category: 'ai',
    parameters: {
      type: 'object',
      properties: {
        prompt: {
          type: 'string',
          description: 'Detailed description of the image to generate. Be descriptive and specific.',
          minLength: 1,
          maxLength: 4000,
        },
        style: {
          type: 'string',
          enum: ['natural', 'vivid'],
          description: 'The style of the generated image. Natural for more subdued, vivid for hyper-real.',
          default: 'natural',
        },
        size: {
          type: 'string',
          enum: ['1024x1024', '1792x1024', '1024x1792'],
          description: 'The size of the generated image',
          default: '1024x1024',
        },
        quality: {
          type: 'string',
          enum: ['standard', 'hd'],
          description: 'The quality of the generated image',
          default: 'standard',
        },
      },
      required: ['prompt'],
    },
    examples: [
      {
        input: { prompt: 'A serene mountain landscape at sunset with a lake reflection' },
        output: { success: true, imageUrl: 'https://...', prompt: 'A serene mountain landscape...' },
        description: 'Generate a nature landscape image',
      },
      {
        input: { prompt: 'A futuristic city with flying cars', style: 'vivid', size: '1792x1024' },
        output: { success: true, imageUrl: 'https://...', prompt: 'A futuristic city...' },
        description: 'Generate a sci-fi cityscape with specific style and size',
      },
    ],
  };

  constructor(
    private readonly fileService: FileService,
    private readonly eventService: EventService,
    @InjectRepository(FileEntity)
    private readonly fileRepository: Repository<FileEntity>,
  ) {
    super();
  }

  protected validateInput(input: unknown): ImageGenerationInput {
    try {
      return imageGenerationInputSchema.parse(input);
    } catch (error) {
      throw new Error(`Invalid input: ${error instanceof Error ? error.message : String(error)}`);
    }
  }

  protected async executeInternal(
    context: ToolExecutionContext,
    input: ImageGenerationInput,
  ): Promise<ImageGenerationOutput> {
    this.logger.debug('Starting image generation', {
      userId: context.userId,
      prompt: input.prompt.substring(0, 100),
      style: input.style,
      size: input.size,
      quality: input.quality,
    });

    try {
      // Call OpenAI DALL-E API
      const response = await this.callOpenAIImageGeneration(input);
      
      if (!response.data || response.data.length === 0) {
        throw new Error('No image generated by OpenAI');
      }

      const imageData = response.data[0];
      const imageUrl = imageData.url;
      const revisedPrompt = imageData.revised_prompt;

      if (!imageUrl) {
        throw new Error('No image URL returned from OpenAI');
      }

      // Download and store the image
      const file = await this.downloadAndStoreImage(context, imageUrl, input.prompt);
      
      // Get signed URL using the public API
      const signedFile = await this.fileService.findOne(context, file.id);

      this.logger.log('Image generated successfully', {
        userId: context.userId,
        fileId: file.id,
        prompt: input.prompt.substring(0, 100),
      });

      return {
        success: true,
        imageUrl: signedFile.url || '',
        fileId: file.id,
        prompt: input.prompt,
        revisedPrompt,
        message: `I've generated an image for you: "${input.prompt}". Here it is:\n\n![Generated Image](${signedFile.url})\n\n${revisedPrompt ? `The prompt was refined to: "${revisedPrompt}"` : ''}`,
      };
    } catch (error) {
      this.logger.error('Image generation failed', {
        userId: context.userId,
        prompt: input.prompt.substring(0, 100),
        error: error instanceof Error ? error.message : String(error),
      });

      return {
        success: false,
        imageUrl: '',
        fileId: '',
        prompt: input.prompt,
        message: `Failed to generate image: ${error instanceof Error ? error.message : 'Unknown error during image generation'}`,
      };
    }
  }

  private async callOpenAIImageGeneration(input: ImageGenerationInput) {
    const openaiApiKey = config.services.openai.apiKey;
    
    if (!openaiApiKey) {
      throw new Error('OpenAI API key not configured');
    }

    const response = await fetch('https://api.openai.com/v1/images/generations', {
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${openaiApiKey}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        model: 'dall-e-3',
        prompt: input.prompt,
        n: 1,
        size: input.size,
        quality: input.quality,
        style: input.style,
        response_format: 'url',
      }),
    });

    if (!response.ok) {
      const errorData = await response.text();
      throw new Error(`OpenAI API error: ${response.status} ${response.statusText} - ${errorData}`);
    }

    return await response.json();
  }

  private async downloadAndStoreImage(
    context: ToolExecutionContext,
    imageUrl: string,
    prompt: string,
  ): Promise<FileEntity> {
    // Download the image
    const imageResponse = await fetch(imageUrl);
    
    if (!imageResponse.ok) {
      throw new Error(`Failed to download image: ${imageResponse.status} ${imageResponse.statusText}`);
    }

    const imageBuffer = await imageResponse.arrayBuffer();
    const buffer = Buffer.from(imageBuffer);

    // Generate filename and IDs
    const timestamp = new Date().toISOString().replace(/[:.]/g, '-');
    const filename = `generated-image-${timestamp}.png`;
    const fileId = uuidv7();
    const fileKey = uuidv4();

    // Create file record using correct FileEntity structure
    const fileEntity = this.fileRepository.create({
      id: fileId,
      bucket: config.staticfiles.bucket,
      key: fileKey,
      original_name: filename,
      content_type: 'image/png',
      size: buffer.length,
      user: {
        id: context.userId,
      },
    });

    // Save to database first to get the record
    const savedFile = await this.fileRepository.save(fileEntity);

    try {
      // Create our own S3 client to upload the file (same pattern as FileService)
      const { S3Client, PutObjectCommand } = await import('@aws-sdk/client-s3');
      
      const s3Client = new S3Client({
        endpoint: config.staticfiles.storageUrl,
        region: config.staticfiles.region || 'us-east-1',
        forcePathStyle: true,
        credentials: {
          accessKeyId: config.staticfiles.auth.accessKeyId,
          secretAccessKey: config.staticfiles.auth.secretAccessKey,
        },
      });
      
      await s3Client.send(
        new PutObjectCommand({
          Bucket: savedFile.bucket,
          Key: savedFile.key,
          Body: buffer,
          ContentType: 'image/png',
        }),
      );

      // Send file upload event like FileService does
      await this.eventService.send(Events.FILE_UPLOAD, {
        fileId: savedFile.id,
      });

      return savedFile;
    } catch (uploadError) {
      // Clean up database record if upload fails
      await this.fileRepository.delete(savedFile.id);
      throw uploadError;
    }
  }
}