function buildAuthEnvTemplate(providerKey: string, legacyPrefix?: string) {
  const normalized = providerKey.toUpperCase().replace(/[^A-Z0-9]+/g, '_');
  const legacy = legacyPrefix?.toUpperCase().replace(/[^A-Z0-9]+/g, '_');

  return {
    modeVar: `PROVIDER_${normalized}_MODE`,
    clientIdVar: `PROVIDER_${normalized}_CLIENT_ID`,
    clientSecretVar: `PROVIDER_${normalized}_CLIENT_SECRET`,
    legacyClientIdVar: legacy ? `${legacy}_CLIENT_ID` : undefined,
    legacyClientSecretVar: legacy ? `${legacy}_CLIENT_SECRET` : undefined,
    testAccessTokenVar: `PROVIDER_${normalized}_TEST_ACCESS_TOKEN`,
    testRefreshTokenVar: `PROVIDER_${normalized}_TEST_REFRESH_TOKEN`,
    mockBaseUrlVar: `PROVIDER_${normalized}_MOCK_BASE_URL`,
  };
}

function stream(input: ProviderStreamDefinition): ProviderStreamDefinition {
  return input;
}

