-- migrate:up
-- Record where each seeded catalogue question sits in the migration that seeded
-- it, so the inference rotation can take the catalogue in its written order —
-- the same order on every appliance.
--
-- WHY. Both selectors of the next question to infer
-- (QuestionService.findUnansweredByUserId and
-- SmartRotationListener.findNextUnansweredQuestionId) broke their last tie on
-- `q.question_id ASC`, on the understanding that a v7 id keeps insertion order.
-- Here it does not. ci.gen_uuid_v7() has minted random UUIDv4 since the PG18
-- image (2026-06-11) dropped the pg_uuidv7 extension its body calls, and no fix
-- to the function can reach the seeded catalogue: a fresh install runs every
-- seed migration before any later one, so a new appliance mints those rows as
-- v4, for good. A seed batch also shares one created_at (now() is fixed for the
-- transaction), so within a batch the uuid tiebreak WAS the order: a random
-- permutation, different on every appliance. Measured on two freshly migrated
-- databases: 1,258 of the 1,279 questions inference may pick carry per-install
-- ids, 1,152 of them in a single created_at, and the first question each
-- offered after "Which of these places is home?" was a different one.
--
-- The written order cannot be recovered from the database — the ids are random
-- and the timestamps tie — so this migration carries it, copied from the seed
-- files themselves. seedPositionBackfill.test.ts re-reads those files and fails
-- if either list below disagrees with them.
--
-- WHAT. `seed_position` is a question's 1-based place across the catalogue's
-- seed migrations: migration order first, then the order each one lists its
-- rows. It is numbered globally rather than per file, so rows from two seeds
-- that share a created_at still fall in written order. NULL for anything no
-- seed migration wrote: a user's own reflections, LLM-generated questions, and a
-- user's private copy of a shared question.
--
-- The selectors do not simply ORDER BY it. Within each tier and created_at
-- batch they take the catalogue round-robin across categories, each category in
-- written order (domains/intelligence/questionOrder.ts). The seed files are laid
-- out category by category, so plain written order would spend a fresh
-- appliance's first hundred or so factual inferences on Health & Body alone.
--
-- HOW ROWS ARE MATCHED.
--   * Seeds that pinned their ids, by id: exact, and the same row everywhere.
--   * The rest by lower(btrim(question_text)), the key those seeds' own
--     NOT EXISTS guards use, among shared rows only.
--   * A shared row whose text was edited after it was seeded matches nothing and
--     stays NULL. The rotation then places it by text within its batch — still
--     the same on every appliance, just not in written order.
--
-- NOTHING ELSE CHANGES. No id is rewritten: ci.answers cascades from
-- question_id, and a client addresses a question by question_key, never by id
-- (docs/api/rest.md, GET /questions/catalogue). updated_at is left alone — this
-- is bookkeeping for the rotation, not an edit anybody made. Idempotent: each
-- UPDATE only fills a NULL.

ALTER TABLE ci.questions
  ADD COLUMN IF NOT EXISTS seed_position integer;

COMMENT ON COLUMN ci.questions.seed_position IS
  '1-based place of a seeded catalogue question across the seed migrations: migration order, then the order each lists its rows. '
  'The inference rotation reads it (round-robin across categories within a tier and created_at batch, see questionOrder.ts) '
  'because question_id order is random per appliance. NULL for rows no seed migration wrote. '
  'A migration that seeds more questions should write it too, continuing past the highest position in use.';

