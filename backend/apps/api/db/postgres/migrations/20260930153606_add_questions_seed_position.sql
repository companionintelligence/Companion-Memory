-- 1. Seeds that pinned their ids: exact, and the same row on every appliance.
--    Where two seeds list the same id the earlier position wins: the later one
--    found the row already there and inserted nothing (20260824232133 re-lists
--    'How tall are you?' under the id 20260730054500 had already given it).
UPDATE ci.questions q
   SET seed_position = s.seed_position
  FROM (
    SELECT DISTINCT ON (i.question_id) i.question_id, i.seed_position
      FROM _seeded_by_id i
     ORDER BY i.question_id, i.seed_position
  ) s
 WHERE q.question_id = s.question_id
   AND q.seed_position IS NULL;

-- 2. Seeds that let the default mint the id, by the key their own NOT EXISTS
--    guards use. Shared rows only: a private copy is not seed content. Where
--    two seeds list the same text the earlier position wins — the later seed's
--    guard skipped it, so the row is the earlier seed's. Runs after step 1 so a
--    pinned row carrying the same text as a catalogue row (the Life details
--    stable ids) keeps its own position.
UPDATE ci.questions q
   SET seed_position = s.seed_position
  FROM (
    SELECT DISTINCT ON (lower(btrim(t.question_text)))
           lower(btrim(t.question_text)) AS text_key,
           t.seed_position
      FROM _seeded_by_text t
     ORDER BY lower(btrim(t.question_text)), t.seed_position
  ) s
 WHERE lower(btrim(q.question_text)) = s.text_key
   AND q.is_private_to IS NULL
   AND q.seed_position IS NULL;

